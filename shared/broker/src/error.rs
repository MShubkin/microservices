use serde::{Deserialize, Serialize};
use thiserror::Error;

pub type Result<T> = std::result::Result<T, BrokerError>;

/// Ошибки слоя брокера сообщений.
///
/// Derive [`Serialize`]/[`Deserialize`] нужен для передачи ошибок через RPC-ответы —
/// сервис может вернуть `BrokerError` в теле AMQP-сообщения, и получатель его распакует.
///
/// `#[non_exhaustive]`: enum может расширяться новыми вариантами без мажорного
/// повышения версии. Внешние `match` обязаны иметь wildcard-arm — это форс
/// корректной обработки неизвестных сетевых ошибок при rolling-update кластера,
/// когда сервисы разных версий обмениваются сериализованными `BrokerError`.
#[derive(Error, Debug, Serialize, Deserialize)]
#[non_exhaustive]
pub enum BrokerError {
    /// Проброс ошибок из `amqprs` — сетевые сбои, ошибки протокола AMQP и т.п.
    #[error("Внутренняя ошибка: `{0}`")]
    Internal(String),

    /// Канал `mpsc` закрыт до истечения таймаута — сообщение так и не пришло.
    #[error("Слишком долгое ожидание сообщения")]
    WaitingTooLong,

    /// Специализация `WaitingTooLong` для `DirectReply`: сервис не ответил вовремя.
    /// Разделение нужно, чтобы вызывающий код различал «нет сообщения» и «нет ответа на RPC».
    #[error("Слишком долгое ожидание ответа на сообщение")]
    WaitingTooLongForReply,

    /// `mpsc::Receiver::recv()` вернул `None` — все отправители канала были дропнуты.
    /// Это означает, что сторона-издатель отключилась; ретрай бессмыслен.
    #[error("Нет отправителей, от которых можно было бы получать сообщения")]
    NoSenders,

    /// Нет подписчиков, которым можно было бы отправить сообщение.
    #[error("Нет получателей для получения сообщения")]
    NoReceivers,

    /// JSON-десериализация входящего payload провалилась. Строка содержит диагностику `serde_json`.
    /// При этом уже отправлен nack, чтобы брокер не застрял с unacked-сообщением.
    #[error("Ошибка при десериализации получаемых данных: `{0}`")]
    InvalidReceivedMessage(String),

    /// JSON-сериализация исходящего payload провалилась. Сообщение в брокер не отправляется.
    #[error("Ошибка при сериализации отправляемых данных: `{0}`")]
    InvalidSentMessage(String),

    /// `basic_ack` на сервер не прошёл. Брокер заново доставит сообщение после переподключения.
    #[error("Не удается отправить подтверждение")]
    SendAck,

    /// `basic_nack` на сервер не прошёл. Поведение брокера с этим сообщением неопределено.
    #[error("Не удается отправить отрицательное подтверждение")]
    SendNack,

    /// Закрыть канал не удалось — обычно это означает, что соединение уже потеряно.
    #[error("Не удается закрыть канал")]
    CloseChannel,
}

/// Все низкоуровневые ошибки `amqprs` сворачиваются в `Internal(String)`,
/// чтобы не тянуть тип `amqprs::error::Error` за пределы этого крейта.
impl From<amqprs::error::Error> for BrokerError {
    fn from(err: amqprs::error::Error) -> Self {
        Self::Internal(err.to_string())
    }
}
