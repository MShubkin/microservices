//! Библиотека `broker` разработана как упрощенная абстракция взаимодействия с
//! брокером сообщений в рамках проекта ASEZ 2.0
//!
//! Чтобы ознакомиться с некоторыми примерами его использования, загляните в каталог `examples`
pub mod error;
pub mod rabbit;
mod retry;

use std::time::Duration;

use async_trait::async_trait;

pub use error::{BrokerError, Result};
pub use retry::RetryArgs;

/// Общий трейт для брокера сообщений.
///
/// Все ассоциированные типы вынесены в трейт, а не захардкожены,
/// чтобы можно было подменить реализацию в тестах или переключиться
/// на другой брокер без изменения кода вызывающих сервисов.
#[async_trait]
pub trait BrokerAdapter {
    /// Мультиплексированный канал внутри одного TCP-соединения (аналог AMQP channel).
    type Channel;
    /// Аргументы для инициализации соединения
    type ConnectionArgs;
    /// Аргументы для объявления очереди
    type QueueArgs;
    /// Метаданные сообщения (content-type, reply-to, expiration и т.п.)
    type BasicProperties;
    /// Аргументы для регистрации консьюмера
    type ConsumeArgs;
    /// Аргументы для регистрации паблишера
    type PublishArgs;

    /// Регистрируемый консьюмер
    type Consumer;
    /// Регистрируемый паблишер
    type Publisher;

    /// # Описание
    ///
    /// Установление соединения с брокером сообщений
    ///
    /// # Аргументы
    ///
    /// * `connection_args` - Аргументы соединения для подключения к серверу брокера сообщений
    /// * `retry_args` - Аргументы retry мезанизма
    ///
    /// # Возвращает
    /// * Ok([`Self`] - Успешное подключение к серверу
    /// * Err([`BrokerError`]) - Ошибка при подключении к серверу
    async fn connect(
        connection_args: Self::ConnectionArgs,
        retry_args: RetryArgs,
    ) -> Result<Self>
    where
        Self: Sized;

    /// # Описание
    ///
    /// Открытие канала брокера для мультиплексирования
    ///
    /// # Аргументы
    /// * `channel_id` - идентификатор конкретного канала
    ///
    /// # Возвращает
    /// * Ok([`Self::Channel`]) - Успешное открытие канала
    /// * Err([`BrokerError`]) - Ошибка при открытии канала
    async fn open_channel(&self, channel_id: Option<u16>) -> Result<Self::Channel>;

    /// # Описание
    ///
    /// Декларация очереди брокера сообщений
    ///
    /// # Аргументы
    /// * `queue_args` - Аргументы для объявления очереди
    ///
    /// # Возвращает
    /// * Ok([`()`]) - Успешная декларация очереди сообщений
    /// * Err([`BrokerError`]) - Ошибка при декларации очереди сообщений
    async fn declare_queue(&self, queue_args: Self::QueueArgs) -> Result<()>;

    /// # Описание
    ///
    /// Регистрация долгоживущего консьюмера
    ///
    /// # Аргументы
    /// * `consume_args` - Аргументы для регистрации консьюмера и консьюма сообщений
    ///
    /// # Возвращает
    /// * Ok([`Self::Consumer`]) - Успешная регистрация консьюмера
    /// * Err([`BrokerError`]) - Ошибка при регистрация консьюмера
    async fn register_consumer(
        &self,
        consume_args: Self::ConsumeArgs,
    ) -> Result<Self::Consumer>;

    /// # Описание
    ///
    /// Регистрация долгоживущего паблишера
    ///
    /// # Аргументы
    /// * `basic_props` - Основные свойства для отправки сообщения
    /// * `publish_args` - Аргументы отправления сообщения
    ///
    /// # Возвращает
    /// * Ok([`Self::Publisher`]) - Успешная регистрация паблишера
    /// * Err([`BrokerError`]) - Ошибка при регистрация паблишера
    async fn register_publisher(
        &self,
        basic_props: Self::BasicProperties,
        publish_args: Self::PublishArgs,
    ) -> Result<Self::Publisher>;

    /// # Описание
    ///
    /// Способ закрытия всех каналов и подключения для плавного завершения работы
    ///
    /// # Возвращает
    /// * Ok([`()`]) - Успешное завершение работы
    /// * Err([`BrokerError`]) - Ошибка при плавном завершении работы
    async fn shutdown(self) -> Result<()>;
}

/// Базовый интерфейс консьюмера.
///
/// Параметр `C` — тип payload после десериализации. Он намеренно вынесен на уровень трейта,
/// а не на уровень метода, чтобы конкретный `RabbitConsumer` мог реализовать `Consumer<MyDto>`
/// и скрыть шаги десериализации внутри.
#[async_trait]
pub trait Consumer<C> {
    /// Полное AMQP-сообщение: помимо `content` содержит `Deliver` (delivery-tag для ack/nack)
    /// и `BasicProperties` (reply-to, correlation-id и др.).
    type Message;

    /// # Описание
    ///
    /// Извлекает сообщение из очереди, и автоматически отправляет подтверждение (на данный момент)
    ///
    /// # Возвращает
    /// * Ok([`Self::Message`]) - Сообщение успешно получено
    /// * Err([`BrokerError::Internal`]) - Ошибка при получении сообщения из очереди
    /// * Err([`BrokerError::InvalidReceivedMessage`]) - Ошибка при десериализации его содержимого
    /// * Err([`BrokerError::NoSenders`]) - Нет ни единого паблишера для данной очереди
    async fn consume(&mut self) -> Result<Self::Message>;

    /// # Описание
    ///
    /// Извлекает сообщение из очереди с определенным таймаутом. Если
    /// извлечение очереди длится дольше таймаута, то операция прерывается
    /// и возвращается [`BrokerError::WaitingTooLong`]
    ///
    /// # Аргументы
    /// * `consume_args` - Аргументы для регистрации консьюмера и консьюма сообщений
    /// * `timeout` - Таймаут, по истечении которого попытка получить сообщение будет
    /// закончена
    ///
    /// # Возвращает
    /// * Ok([`Self::Message`]) - Сообщение успешно получено
    /// * Err([`BrokerError::Internal`]) - Ошибка при получении сообщения из очереди
    /// * Err([`BrokerError::WaitingTooLong`]) - Слишком долгое ожидание сообщения
    /// * Err([`BrokerError::InvalidReceivedMessage`]) - Ошибка при десериализации его содержимого
    /// * Err([`BrokerError::NoSenders`]) - Нет ни единого паблишера для данной очереди
    async fn consume_with_timeout(
        &mut self,
        timout: Duration,
    ) -> Result<Self::Message>;

    /// # Описание
    ///
    /// Отправляет подтверждение об успешном получении сообщения.
    /// Не забывайте, что [`Consumer::consume`] также может отправлять подтверждение при успешном получении
    /// Сообщения. Двойная отправка подтверждения с тем же [`Self::Message`] может привести к ошибке.
    ///
    /// # Аргументы
    ///  `message` - Полученные сообщение с метадатой
    ///
    /// # Возвращает
    /// * Ok([`()`]) - Подтверждение успешно отправлено
    /// * Err([`BrokerError`]) - Ошибка при отправлении подтверждения
    async fn send_ack(&self, message: &Self::Message) -> Result<()>;

    /// # Описание
    ///
    /// Отправляет уведомление об ошибке, указывая на то, что сообщение не было доставлено.
    /// Не забывайте, что [`Consumer::consume`] также может отправить nack, если произошла непредвиденная ошибка
    /// при получении сообщения, например при неудачной десериализации.
    /// Двойная отправка с одним и тем же [`Self::Message`] может привести к ошибке.
    ///
    /// # Аргументы
    ///  `message` - Полученные сообщение с метадатой
    ///
    /// # Возвращает
    /// * Ok([`()`]) - Подтверждение успешно отправлено
    /// * Err([`BrokerError`]) - Ошибка при отправлении подтверждения
    async fn send_nack(&self, message: &Self::Message) -> Result<()>;
}

/// Базовый интерфейс паблишера.
///
/// Параметр `C` — тип payload до сериализации. `publish` принимает `&C`, а не
/// `C`, чтобы тот же объект можно было отправить несколько раз без клонирования.
#[async_trait]
pub trait Publisher<C> {
    /// # Описание
    ///
    /// Публикует сообщение в очередь
    ///
    /// # Аргументы
    /// * `content` - Любое содержимое, которое может быть сериализовано и отправлено
    ///
    /// # Возвращает
    /// * Ok([`()`]) - Сообщение успешно отправлено
    /// * Err([`BrokerError::Internal`]) - Ошибка при отправке сообщения в очередь
    /// * Err([`BrokerError::InvalidSentMessage`]) - Ошибка при сериализации отправляемых данных
    async fn publish(&self, content: &C) -> Result<()>;
}
