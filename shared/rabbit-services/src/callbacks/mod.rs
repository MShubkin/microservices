//! Коллбэки, вызываемые при публикации AMQP-сообщений.
//!
//! Коллбэки регистрируются в [`DirectReply`](broker::rabbit::adapter::DirectReply)
//! через [`AsezRabbitService::with_callback`] и выполняются после каждой публикации.
//! Это позволяет добавлять сквозное поведение (логирование, метрики) без изменения
//! логики конкретного сервиса.

pub mod log_callback;

/// Перечень доступных коллбэков для регистрации в сервисах.
///
/// Enum нужен, чтобы набор коллбэков хранился как `Vec<AsezCallback>` без dyn-указателей
/// и легко клонировался.
#[derive(Clone, Debug)]
pub enum AsezCallback {
    /// Отправляет запись в сервис хранения логов при каждой публикации.
    LogStorageCallback,
}
