//! Инфраструктура для интеграционных тестов АСЭЗ.
//!
//! Ключевая проблема: тесты запускаются параллельно (`cargo test` по умолчанию),
//! но им нужна изолированная БД. Решение — числовые суффиксы: `dbname_0`, `dbname_1`...
//! Каждый тест получает свой номер через `FreeId`, а значит свою БД.
//!
//! При первом запуске теста на конкретной БД: `DROP SCHEMA CASCADE` + миграции.
//! При повторном использовании той же БД (в пуле): только TRUNCATE пустых таблиц.
//! Это ускоряет тест-сьюты примерно в 10 раз по сравнению с пересозданием схемы.
//!
//! Для регистрации `TestHarness`-ресурсов используется атрибут-макрос `#[test]`
//! из крейта `asez_macros` — он разворачивает параметры тестовой функции
//! в вызовы `TestHarness::initialize().await`.

